/**
 * A pinned runtime is an exact release archive unpacked into
 * <baseDir>/runtime/versions/<version>: the self-contained executable, the
 * web client, and the native packages beside it. The boot service points its
 * unit or launch agent at the executable, and server self-update installs the
 * target version here before switching over. The runtime never depends on a
 * Node or npm on the machine; the only npm involvement in T3 Code is the `t3`
 * package for people who prefer `npx t3` or `npm install -g t3`, and even a
 * CLI installed that way pins an archive when it sets up the service.
 */
const PINNED_RUNTIME_DIR = "runtime";
const PINNED_RUNTIME_INSTALL_TIMEOUT = Duration.minutes(10);
const PINNED_RUNTIME_ARCHIVE_FILE = "cogenly-runtime-archive";
/** Step names `cogenly update` matches to report a release without a Linux archive. */
export const PINNED_RUNTIME_CHECKSUMS_STEP = "downloading the release checksums";
export const PINNED_RUNTIME_ARCHIVE_MISSING_STEP = "finding the release archive in the checksums";
// Boot-service setup and remote update can construct separate layers. Serialize
// the complete install transaction across every caller in this process.
const pinnedRuntimeInstallLock = Semaphore.makeUnsafe(1);

export interface PinnedRuntimePaths {
  readonly versionDir: string;
  /** The executable. Its existence is what marks a runtime as present. */
  readonly entryPath: string;
  readonly sentinelPath: string;
}

/**
 * A source checkout the service can pin instead of a release archive: the
 * Node running this CLI plus the CLI entry it runs.
 */
export interface CheckoutRuntime {
  readonly nodePath: string;
  readonly entryPath: string;
}

/**
 * Detects a checkout invocation: plain Node running a script, rather than a
 * single-executable. `scriptArg` is `process.argv[1]`; anything else (a CLI
 * subcommand, a missing arg) means this is not a checkout run and archive
 * resolution proceeds. The caller verifies the entry exists.
 */
export function resolveCheckoutRuntime(input: {
  readonly isExecutable: boolean;
  readonly nodePath: string;
  readonly scriptArg: string | undefined;
  readonly resolveEntry: (script: string) => string;
}): CheckoutRuntime | undefined {
  if (input.isExecutable) return undefined;
  const script = input.scriptArg?.trim();
  if (!script) return undefined;
  return { nodePath: input.nodePath, entryPath: input.resolveEntry(script) };
}

/** Single-quote a value for POSIX `sh`, escaping embedded quotes. */
export function quoteShellArg(value: string): string {
  return `'${value.replaceAll("'", "'\\''")}'`;
}

/**
 * The pinned entry for a checkout install: a script that execs the
 * checkout's CLI, so the launcher, status checks, and validation all work
 * unchanged. Updating means rebuilding the checkout and restarting the
 * service; only a moved checkout needs a reinstall.
 */
export function renderCheckoutWrapper(checkout: CheckoutRuntime): string {
  return [
    "#!/bin/sh",
    "# Generated by `cogenly service install` for a source checkout.",
    `exec ${quoteShellArg(checkout.nodePath)} ${quoteShellArg(checkout.entryPath)} "$@"`,
    "",
  ].join("\n");
}

/** The exact command that runs a pinned runtime. */
export function pinnedRuntimeCommand(paths: PinnedRuntimePaths): {
  readonly command: string;
  readonly args: ReadonlyArray<string>;
} {
  return { command: paths.entryPath, args: [] };
}

export function pinnedRuntimeVersionsDir(path: Path.Path, baseDir: string): string {
  return path.join(baseDir, PINNED_RUNTIME_DIR, "versions");
}

export function pinnedRuntimePaths(
  path: Path.Path,
  baseDir: string,
  version: string,
  platform: NodeJS.Platform,
): PinnedRuntimePaths {
  const versionDir = path.join(pinnedRuntimeVersionsDir(path, baseDir), version);
  return {
    versionDir,
    entryPath: path.join(versionDir, cliExecutableFileName(platform)),
    sentinelPath: path.join(versionDir, ".install-complete"),
  };
}

/**
 * `paths` with the executable that is actually on disk: `cogenly`, else the
 * `t3` of a runtime unpacked from an archive older than the rename. A
 * runtime with neither keeps the `cogenly` path. Remove the `t3` fallback
 * only as "Transition: t3 → cogenly names" in docs/operations/release.md
 * describes.
 */
export const resolvePinnedRuntimeEntry = Effect.fn("cloud.pinned_runtime.resolve_entry")(function* (
  fs: FileSystem.FileSystem,
  path: Path.Path,
  paths: PinnedRuntimePaths,
  platform: NodeJS.Platform,
) {
  if (yield* fs.exists(paths.entryPath)) return paths;
  const legacy = path.join(
    paths.versionDir,
    cliExecutableFileName(platform, LEGACY_CLI_EXECUTABLE_NAME),
  );
  return (yield* fs.exists(legacy)) ? { ...paths, entryPath: legacy } : paths;
});

export class PinnedRuntimeInstallError extends Schema.TaggedError<PinnedRuntimeInstallError>()(
  "PinnedRuntimeInstallError",
  {
    step: Schema.String,
    exitCode: Schema.optional(Schema.Number),
    stdoutLength: Schema.optional(Schema.Number),
    stderrLength: Schema.optional(Schema.Number),
    cause: Schema.optional(Schema.Defect()),
  },
) {
  override get message(): string {
    return this.exitCode === undefined
      ? `Pinned runtime install failed while ${this.step}.`
      : `Pinned runtime install failed while ${this.step} (exit code ${this.exitCode}).`;
  }
}

export class PinnedRuntimePreflightBlockedError extends Schema.TaggedError<PinnedRuntimePreflightBlockedError>()(
  "PinnedRuntimePreflightBlockedError",
  {
    version: Schema.String,
    reason: Schema.String,
  },
) {
  override get message(): string {
    return this.reason;
  }
}

export type PinnedRuntimeProgress =
  | { readonly stage: "download"; readonly received: number; readonly total: number | undefined }
  | { readonly stage: "verify" | "extract" | "validate" | "cached" };

/**
 * Installs the release archive for `version` into the pinned runtime
 * directory unless a complete install is already there, and returns its
 * paths. The sentinel is written only after extraction and validation
 * succeed; checking the entry file alone is not enough, since tar writes the
 * executable before the last native package and a killed install leaves a
 * plausible-looking but broken tree behind.
 */

interface PinnedRuntimeInstallInput {
  readonly baseDir: string;
  readonly version: string;
  readonly fs: FileSystem.FileSystem;
  readonly path: Path.Path;
  readonly runner: ProcessRunner.ProcessRunner["Service"];
  readonly validate: (
    paths: PinnedRuntimePaths,
  ) => Effect.Effect<void, PinnedRuntimeInstallError | PinnedRuntimePreflightBlockedError>;
  readonly platform: NodeJS.Platform;
  readonly arch: string;
  readonly httpClient: HttpClient.HttpClient;
  readonly releaseBaseUrl?: string | undefined;
  readonly onProgress?: (progress: PinnedRuntimeProgress) => void;
  /**
   * Pin a wrapper that execs this checkout's CLI instead of downloading a
   * release archive. Absent outside checkout invocations.
   */
  readonly checkout?: CheckoutRuntime | undefined;
}

const fetchReleaseAsset = Effect.fn("cloud.pinned_runtime.fetch_release_asset")(function* (
  httpClient: HttpClient.HttpClient,
  url: string,
  step: string,
  onProgress?: (progress: PinnedRuntimeProgress) => void,
) {
  // The install lock is held for the whole transaction, so a stalled download
  // must fail rather than block every other caller.
  return yield* httpClient.execute(HttpClientRequest.get(url)).pipe(
    Effect.flatMap(HttpClientResponse.filterStatusOk),
    Effect.flatMap(
      Effect.fn(function* (response) {
        if (onProgress === undefined) return new Uint8Array(yield* response.arrayBuffer);
        const length = Number(response.headers["content-length"]);
        const total = Number.isFinite(length) && length > 0 ? length : undefined;
        let received = 0;
        onProgress({ stage: "download", received, total });
        const chunks = yield* response.stream.pipe(
          Stream.tap((chunk) =>
            Effect.sync(() => {
              received += chunk.byteLength;
              onProgress({ stage: "download", received, total });
            }),
          ),
          Stream.runCollect,
        );
        // A completed chunked response finally gives us its total size.
        if (total === undefined && received > 0) {
          onProgress({ stage: "download", received, total: received });
        }
        const bytes = new Uint8Array(received);
        let offset = 0;
        for (const chunk of chunks) {
          bytes.set(chunk, offset);
          offset += chunk.byteLength;
        }
        return bytes;
      }),
    ),
    Effect.mapError((cause) => new PinnedRuntimeInstallError({ step, cause })),
    Effect.timeoutOrElse({
      duration: PINNED_RUNTIME_INSTALL_TIMEOUT,
      orElse: () => Effect.fail(new PinnedRuntimeInstallError({ step: `${step} (timed out)` })),
    }),
  );
});

/**
 * Downloads the release archive for this platform, verifies it against the
 * release's checksum file, and unpacks it so the executable sits directly in
 * the staging directory. Only `tar` is required on the host; every supported
 * OS ships one that reads gzip and zip.
 */
const installFromArchive = Effect.fn("cloud.pinned_runtime.install_archive")(function* (
  input: PinnedRuntimeInstallInput,
  stagingDir: string,
  baseUrl: string,
) {
  const { fs, path } = input;
  const platformKey = cliArchivePlatformKey(input.platform, input.arch);
  if (platformKey === undefined) {
    return yield* new PinnedRuntimeInstallError({
      step: `selecting a release archive for ${input.platform}-${input.arch} (Cogenly releases ship Linux x64 and arm64 servers; elsewhere use the desktop app or a source checkout)`,
    });
  }
  const httpClient = input.httpClient;

  input.onProgress?.({ stage: "download", received: 0, total: undefined });
  const checksums = parseChecksums(
    new TextDecoder().decode(
      yield* fetchReleaseAsset(
        httpClient,
        `${baseUrl}/${CLI_RELEASE_CHECKSUMS_FILE}`,
        PINNED_RUNTIME_CHECKSUMS_STEP,
      ),
    ),
  );
  // Releases from before the rename list only the t3- name; the checksum
  // file says which one exists, so no download is tried that would 404.
  const selected = selectCliArchive(checksums, input.version, platformKey);
  if (selected === undefined) {
    return yield* new PinnedRuntimeInstallError({
      step: `${PINNED_RUNTIME_ARCHIVE_MISSING_STEP} (${cliArchiveFileName(input.version, platformKey)})`,
    });
  }
  const archive = yield* fetchReleaseAsset(
    httpClient,
    `${baseUrl}/${selected.fileName}`,
    "downloading the release archive",
    input.onProgress,
  );
  input.onProgress?.({ stage: "verify" });
  const digest = yield* Effect.tryPromise({
    try: () => crypto.subtle.digest("SHA-256", archive),
    catch: (cause) =>
      new PinnedRuntimeInstallError({ step: "verifying the release archive", cause }),
  });
  if (Hex.encode(new Uint8Array(digest)) !== selected.sha256) {
    return yield* new PinnedRuntimeInstallError({
      step: "verifying the release archive checksum",
    });
  }

  const archivePath = path.join(stagingDir, PINNED_RUNTIME_ARCHIVE_FILE);
  yield* fs
    .writeFile(archivePath, archive)
    .pipe(
      Effect.mapError(
        (cause) => new PinnedRuntimeInstallError({ step: "writing the release archive", cause }),
      ),
    );
  input.onProgress?.({ stage: "extract" });
  const extractStep = "extracting the release archive";
  // The archive wraps everything in one directory named after its stem;
  // strip it so the executable lands at <versionDir>/cogenly.
  yield* input.runner
    .run({
      command: cliArchiveTarCommand(input.platform, process.env),
      args: ["-xf", archivePath, "-C", stagingDir, "--strip-components=1"],
      timeout: PINNED_RUNTIME_INSTALL_TIMEOUT,
    })
    .pipe(
      Effect.mapError((cause) => new PinnedRuntimeInstallError({ step: extractStep, cause })),
      Effect.filterOrFail(
        (result) => result.code === 0,
        (result) =>
          new PinnedRuntimeInstallError({
            step: extractStep,
            exitCode: Number(result.code),
            stdoutLength: result.stdout.length,
            stderrLength: result.stderr.length,
          }),
      ),
    );
  yield* fs.remove(archivePath, { force: true }).pipe(Effect.ignore);
});

/**
 * Pins a source checkout by writing a wrapper that execs its CLI. Only the
 * wrapper lives in the version directory; the checkout itself keeps serving
 * the code, so updating means rebuilding it and restarting the service.
 */
const installFromCheckout = Effect.fn("cloud.pinned_runtime.install_checkout")(function* (
  input: PinnedRuntimeInstallInput,
  stagingPaths: PinnedRuntimePaths,
  checkout: CheckoutRuntime,
) {
  const { fs } = input;
  yield* fs
    .writeFileString(stagingPaths.entryPath, renderCheckoutWrapper(checkout))
    .pipe(
      Effect.mapError(
        (cause) => new PinnedRuntimeInstallError({ step: "writing the checkout wrapper", cause }),
      ),
    );
  yield* fs
    .chmod(stagingPaths.entryPath, 0o755)
    .pipe(
      Effect.mapError(
        (cause) => new PinnedRuntimeInstallError({ step: "writing the checkout wrapper", cause }),
      ),
    );
});

const installRuntime = Effect.fn("cloud.pinned_runtime.install")(function* (
  input: PinnedRuntimeInstallInput,
  stagingDir: string,
  stagingPaths: PinnedRuntimePaths,
) {
  // A CLI run from a checkout pins that checkout: it is the code being run,
  // and its version may never have been released.
  if (input.checkout !== undefined) {
    yield* Effect.logInfo(
      `Pinning the source checkout at ${input.checkout.entryPath} as cogenly@${input.version}. Rebuild the checkout and restart the service to update.`,
    );
    return yield* installFromCheckout(input, stagingPaths, input.checkout);
  }
  const baseUrl = cliReleaseDownloadBaseUrl(input.version, input.releaseBaseUrl);
  if (baseUrl !== null) {
    return yield* installFromArchive(input, stagingDir, baseUrl);
  }
  return yield* new PinnedRuntimeInstallError({
    step: `locating a release to download (${CLI_RELEASES_UNAVAILABLE_MESSAGE} Set ${CLI_RELEASE_BASE_URL_ENV} to a release mirror)`,
  });
});

const installPinnedRuntime = Effect.fn("cloud.pinned_runtime.ensure_installed")(function* (
  input: PinnedRuntimeInstallInput,
) {
  const { fs } = input;
  const resolveEntry = (candidate: PinnedRuntimePaths, step: string) =>
    resolvePinnedRuntimeEntry(fs, input.path, candidate, input.platform).pipe(
      Effect.mapError((cause) => new PinnedRuntimeInstallError({ step, cause })),
    );
  const paths = yield* resolveEntry(
    pinnedRuntimePaths(input.path, input.baseDir, input.version, input.platform),
    "checking the pinned runtime",
  );
  const [versionDirExists, entryExists, sentinel] = yield* Effect.all([
    fs.exists(paths.versionDir),
    fs.exists(paths.entryPath),
    fs.readFileString(paths.sentinelPath).pipe(Effect.option),
  ]).pipe(
    Effect.mapError(
      (cause) => new PinnedRuntimeInstallError({ step: "checking the pinned runtime", cause }),
    ),
  );
  const alreadyPinned =
    entryExists && Option.isSome(sentinel) && sentinel.value.trim() === input.version;
  if (alreadyPinned) {
    input.onProgress?.({ stage: "cached" });
    yield* input.validate(paths);
    return paths;
  }
  if (versionDirExists) {
    yield* fs.remove(paths.versionDir, { recursive: true, force: true }).pipe(
      Effect.mapError(
        (cause) =>
          new PinnedRuntimeInstallError({
            step: "removing an incomplete pinned runtime",
            cause,
          }),
      ),
    );
  }

  const versionsDir = input.path.dirname(paths.versionDir);
  yield* fs.makeDirectory(versionsDir, { recursive: true }).pipe(
    Effect.mapError(
      (cause) =>
        new PinnedRuntimeInstallError({
          step: "preparing the pinned runtime directory",
          cause,
        }),
    ),
  );
  const stagingDir = yield* fs
    .makeTempDirectory({
      directory: versionsDir,
      prefix: ".staging-",
    })
    .pipe(
      Effect.mapError(
        (cause) =>
          new PinnedRuntimeInstallError({
            step: "preparing the pinned runtime directory",
            cause,
          }),
      ),
    );
  const stagingPaths: PinnedRuntimePaths = {
    versionDir: stagingDir,
    entryPath: input.path.join(stagingDir, input.path.relative(paths.versionDir, paths.entryPath)),
    sentinelPath: input.path.join(stagingDir, ".install-complete"),
  };

  return yield* Effect.gen(function* () {
    yield* installRuntime(input, stagingDir, stagingPaths);
    // An archive from before the rename unpacks only `t3`.
    const installed = yield* resolveEntry(stagingPaths, "checking the unpacked release archive");
    const published = {
      ...paths,
      entryPath: input.path.join(paths.versionDir, input.path.basename(installed.entryPath)),
    };

    input.onProgress?.({ stage: "validate" });
    yield* input.validate(installed);
    yield* fs
      .writeFileString(installed.sentinelPath, `${input.version}\n`)
      .pipe(
        Effect.mapError(
          (cause) =>
            new PinnedRuntimeInstallError({ step: "recording the completed install", cause }),
        ),
      );
    const renamed = yield* fs.rename(stagingDir, paths.versionDir).pipe(
      Effect.as(true),
      Effect.catch((cause) =>
        Effect.all([
          fs.exists(published.entryPath),
          fs.readFileString(paths.sentinelPath).pipe(Effect.option),
        ]).pipe(
          Effect.mapError(
            (checkCause) =>
              new PinnedRuntimeInstallError({
                step: "checking a concurrently published pinned runtime",
                cause: checkCause,
              }),
          ),
          Effect.flatMap(([publishedEntryExists, publishedSentinel]) =>
            publishedEntryExists &&
            Option.isSome(publishedSentinel) &&
            publishedSentinel.value.trim() === input.version
              ? Effect.succeed(false)
              : Effect.fail(
                  new PinnedRuntimeInstallError({
                    step: "publishing the pinned runtime",
                    cause,
                  }),
                ),
          ),
        ),
      ),
    );
    if (!renamed) yield* input.validate(published);
    return published;
  }).pipe(
    Effect.ensuring(fs.remove(stagingDir, { recursive: true, force: true }).pipe(Effect.ignore)),
  );
});

export const ensurePinnedRuntimeInstalled = (input: PinnedRuntimeInstallInput) =>
  pinnedRuntimeInstallLock.withPermit(installPinnedRuntime(input));
