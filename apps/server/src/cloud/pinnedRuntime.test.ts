import { describe, expect, it } from "@effect/vitest";
import * as NodeServices from "@effect/platform-node/NodeServices";
import * as Effect from "effect/Effect";
import * as FileSystem from "effect/FileSystem";
import * as Layer from "effect/Layer";
import * as Path from "effect/Path";
import * as Schema from "effect/Schema";
import { FetchHttpClient, HttpClient } from "effect/http";

import * as ProcessRunner from "../processRunner.ts";
import {
  ensurePinnedRuntimeInstalled,
  PinnedRuntimeInstallError,
  quoteShellArg,
  renderCheckoutWrapper,
  resolveCheckoutRuntime,
} from "./pinnedRuntime.ts";

describe("checkout runtime detection", () => {
  const resolveEntry = (script: string) => `/repo/${script}`;

  it("detects plain Node running a script", () => {
    expect(
      resolveCheckoutRuntime({
        isExecutable: false,
        nodePath: "/opt/homebrew/bin/node",
        scriptArg: "apps/server/dist/bin.mjs",
        resolveEntry,
      }),
    ).toEqual({
      nodePath: "/opt/homebrew/bin/node",
      entryPath: "/repo/apps/server/dist/bin.mjs",
    });
  });

  const nonCheckoutCases: Array<
    [label: string, isExecutable: boolean, scriptArg: string | undefined]
  > = [
    ["single-executable", true, "apps/server/dist/bin.mjs"],
    ["missing script arg", false, undefined],
    ["blank script arg", false, "   "],
  ];
  it.each(nonCheckoutCases)("resolves no checkout for %s", (_label, isExecutable, scriptArg) => {
    expect(
      resolveCheckoutRuntime({
        isExecutable,
        nodePath: "/opt/homebrew/bin/node",
        scriptArg,
        resolveEntry,
      }),
    ).toBeUndefined();
  });

  it("leaves entry existence to the caller", () => {
    // A subcommand in argv[1] (odd wrappers) resolves to a path the caller
    // rejects when it does not exist, falling back to archive resolution.
    expect(
      resolveCheckoutRuntime({
        isExecutable: false,
        nodePath: "/opt/homebrew/bin/node",
        scriptArg: "service",
        resolveEntry,
      }),
    ).toEqual({ nodePath: "/opt/homebrew/bin/node", entryPath: "/repo/service" });
  });
});

describe("checkout wrapper", () => {
  it("quotes paths for sh", () => {
    expect(quoteShellArg("/plain/path")).toBe("'/plain/path'");
    expect(quoteShellArg("/my dir/node")).toBe("'/my dir/node'");
    expect(quoteShellArg("/o'brien/bin.mjs")).toBe("'/o'\\''brien/bin.mjs'");
  });

  it("execs the checkout CLI with its arguments", () => {
    expect(
      renderCheckoutWrapper({ nodePath: "/my dir/node", entryPath: "/repo/dist/bin.mjs" }),
    ).toBe(
      "#!/bin/sh\n" +
        "# Generated by `cogenly service install` for a source checkout.\n" +
        `exec '/my dir/node' '/repo/dist/bin.mjs' "$@"\n`,
    );
  });
});

describe("checkout runtime install", () => {
  const layer = Layer.merge(
    ProcessRunner.layer.pipe(Layer.provideMerge(NodeServices.layer)),
    FetchHttpClient.layer,
  );

  it.effect("pins a wrapper that runs the checkout CLI", () =>
    Effect.gen(function* () {
      const fs = yield* FileSystem.FileSystem;
      const path = yield* Path.Path;
      const runner = yield* ProcessRunner.ProcessRunner;
      const httpClient = yield* HttpClient.HttpClient;
      const root = yield* fs.makeTempDirectoryScoped({ prefix: "t3-checkout-runtime-" });
      const entryPath = path.join(root, "fake-bin.mjs");
      yield* fs.writeFileString(entryPath, '#!/bin/sh\necho "cogenly v9.9.9"\n');
      const validate: Parameters<typeof ensurePinnedRuntimeInstalled>[0]["validate"] = (runtime) =>
        runner.run({ command: runtime.entryPath, args: ["--version"], timeout: "30 seconds" }).pipe(
          Effect.mapError((cause) => new PinnedRuntimeInstallError({ step: "verifying", cause })),
          Effect.flatMap((result) =>
            result.code === 0 && /\bv(\S+)\s*$/.exec(result.stdout)?.[1] === "9.9.9"
              ? Effect.void
              : Effect.fail(
                  new PinnedRuntimeInstallError({
                    step: "verifying",
                    exitCode: Number(result.code),
                  }),
                ),
          ),
        );
      const input = {
        baseDir: path.join(root, "home"),
        version: "9.9.9",
        fs,
        path,
        runner,
        platform: "darwin" as const,
        arch: "arm64",
        httpClient,
        checkout: { nodePath: "/bin/sh", entryPath },
        validate,
      };
      const paths = yield* ensurePinnedRuntimeInstalled(input);
      expect(yield* fs.exists(paths.entryPath)).toBe(true);
      expect(yield* fs.readFileString(paths.sentinelPath)).toBe("9.9.9\n");
      // The pinned entry executes directly, proving the executable bit.
      const direct = yield* runner.run({
        command: paths.entryPath,
        args: ["--version"],
        timeout: "30 seconds",
      });
      expect(direct.code).toBe(0);
      expect(direct.stdout).toContain("v9.9.9");
      // A second install reuses the complete runtime.
      expect(yield* ensurePinnedRuntimeInstalled(input)).toEqual(paths);
    }).pipe(Effect.provide(layer)),
  );

  it.effect("names the supported platforms when releases have no archive for this one", () =>
    Effect.gen(function* () {
      const fs = yield* FileSystem.FileSystem;
      const path = yield* Path.Path;
      const runner = yield* ProcessRunner.ProcessRunner;
      const httpClient = yield* HttpClient.HttpClient;
      const root = yield* fs.makeTempDirectoryScoped({ prefix: "t3-checkout-absent-" });
      const error = yield* ensurePinnedRuntimeInstalled({
        baseDir: path.join(root, "home"),
        version: "9.9.9",
        fs,
        path,
        runner,
        platform: "darwin",
        arch: "arm64",
        httpClient,
        validate: () => Effect.void,
      }).pipe(Effect.flip);
      const isInstallError = Schema.is(PinnedRuntimeInstallError);
      expect(isInstallError(error)).toBe(true);
      if (isInstallError(error)) {
        // Rejected before any download: macOS servers come from the desktop app.
        expect(error.step).toContain("selecting a release archive for darwin-arm64");
        expect(error.step).toContain("Linux x64 and arm64");
      }
    }).pipe(Effect.provide(layer)),
  );
});
